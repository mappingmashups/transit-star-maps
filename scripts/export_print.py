"""Collect the print files for the maps on the website into outputs/print/.

    .venv/bin/python scripts/export_print.py

Copies each listed map's transparent PNG (300 dpi, for dark shirts) to
outputs/print/transit-star-map-<city>.png and writes outputs/print/README.md
with each file's pixel and print size. Re-run after re-rendering maps.
"""

import struct
import shutil
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "outputs" / "print"


def png_info(path):
    data = path.read_bytes()
    w, h = struct.unpack(">II", data[16:24])
    dpi = None
    i = data.find(b"pHYs")
    if i > 0:
        ppm = struct.unpack(">I", data[i + 4:i + 8])[0]
        dpi = round(ppm * 0.0254)
    return w, h, dpi


# Zazzle listing drafts, following the pattern used for the first upload:
# title "Transit Star Map: MARTA (Atlanta, Georgia)", description "Atlanta,
# Georgia's MARTA transit system as if it were a constellation!"
LISTING = {
    "bart": ("BART", "San Francisco Bay Area, California", "the San Francisco Bay Area's BART system",
             ["bart", "san francisco", "bay area", "oakland"]),
    "dc_metro": ("Metrorail", "Washington, D.C.", "Washington, D.C.'s Metrorail system",
                 ["dc metro", "washington dc", "wmata"]),
    "boston_mbta": ("MBTA", "Boston, Massachusetts", "Boston's MBTA subway, the T,",
                    ["mbta", "boston", "the t"]),
    "montreal": ("Métro", "Montréal, Québec", "Montréal's Métro",
                 ["montreal", "stm", "quebec"]),
    "bc_skytrain": ("SkyTrain", "Vancouver, British Columbia", "Vancouver's SkyTrain",
                    ["skytrain", "vancouver", "translink"]),
    "la_metro": ("Metro Rail", "Los Angeles, California", "Los Angeles' Metro Rail system",
                 ["la metro", "los angeles", "metro rail"]),
    "toronto": ("TTC Subway", "Toronto, Ontario", "Toronto's TTC subway",
                ["ttc", "toronto", "ontario"]),
    "trimet_max": ("MAX Light Rail", "Portland, Oregon", "Portland's MAX light rail",
                   ["max", "trimet", "portland"]),
    "seattle_st3": ("Link Light Rail", "Seattle, Washington",
                    "Seattle's Link light rail at its full Sound Transit 3 build-out,",
                    ["link light rail", "seattle", "sound transit"]),
    "cahsr": ("High-Speed Rail", "California", "California High-Speed Rail's full planned network,",
              ["high speed rail", "california", "hsr"]),
    "atlanta_marta": ("MARTA", "Atlanta, Georgia", "Atlanta, Georgia's MARTA transit system",
                      ["marta", "atlanta", "georgia"]),
}
BASE_TAGS = ["subway", "transit", "metro", "constellation", "star map", "transit map", "train"]


def listings(site):
    out = ["# Zazzle listing drafts", "",
           "Generated by `scripts/export_print.py` from its LISTING table; edit there, not here.", ""]
    for e in site["maps"]:
        system, place, phrase, tags = LISTING.get(e["city"], (e["system"], e["place"], e["place"] + "'s " + e["system"], []))
        title = f"Transit Star Map: {system} ({place})"
        desc = f"{phrase[0].upper() + phrase[1:]} as if it were a constellation! Every star is a station, placed where it really is."
        all_tags = list(dict.fromkeys(BASE_TAGS + tags))[:10]
        status = f"[listed]({e['shop']})" if e.get("shop") else "not listed yet"
        out += [f"## {e['place']} · {e['system']} ({status})", "",
                f"- File: `transit-star-map-{e['city'].replace('_', '-')}.png`",
                f"- Title: {title}", f"- Description: {desc}", f"- Tags: {', '.join(all_tags)}", ""]
    (OUT / "LISTINGS.md").write_text("\n".join(out))


def main():
    site = yaml.safe_load((ROOT / "site" / "maps.yaml").read_text())
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    lines = [
        "# Print files",
        "",
        "Transparent PNGs of the maps on the website, for dark shirts (light gray",
        "lines, pale yellow stars). Generated by `scripts/export_print.py`; don't edit.",
        "",
        "| File | Map | Pixels | Print size at 300 dpi |",
        "|---|---|---|---|",
    ]
    for e in site["maps"]:
        city = e["city"]
        src = ROOT / "outputs" / city / f"{city}_transparent.png"
        if not src.exists():
            sys.exit(f"missing {src.relative_to(ROOT)}; run `python -m starmaps render {city}`")
        dest = OUT / f"transit-star-map-{city.replace('_', '-')}.png"
        shutil.copyfile(src, dest)
        w, h, dpi = png_info(dest)
        dpi = dpi or 300
        lines.append(f"| `{dest.name}` | {e['place']} · {e['system']} | {w} × {h} | "
                     f"{w / dpi:.1f} × {h / dpi:.1f} in |")
        print(f"{dest.relative_to(ROOT)}  {w}x{h}  {w / dpi:.1f}x{h / dpi:.1f} in")
    (OUT / "README.md").write_text("\n".join(lines) + "\n")
    listings(site)


if __name__ == "__main__":
    main()
